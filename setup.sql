-- DataMind Snowflake setup. Run once in a Snowsight worksheet as ACCOUNTADMIN (Run all). Safe to run again.
-- Uses your own login automatically. If a GRANT ROLE line errors on IDENTIFIER($me),
-- replace IDENTIFIER($me) with your username (run SELECT CURRENT_USER(); to see it).
--
-- Layout: one database per data source, each with its tables in the PUBLIC schema.
--   SNOWFLAKE_SAMPLE_DATA   TPC-H and TPC-DS samples shared by Snowflake (read in place)
--   UCI                     UCI Machine Learning Repository tables, loaded by load_data.py
--   OWID                    Our World in Data tables, loaded by load_data.py

USE ROLE ACCOUNTADMIN;
SET me = '"' || CURRENT_USER() || '"';  -- quoted so lowercase usernames resolve

CREATE WAREHOUSE IF NOT EXISTS DM_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS UCI;
CREATE DATABASE IF NOT EXISTS OWID;

-- Read-only role used by the app (it can only SELECT).
CREATE ROLE IF NOT EXISTS DM_READER;
GRANT USAGE ON WAREHOUSE DM_WH TO ROLE DM_READER;
GRANT USAGE ON DATABASE UCI TO ROLE DM_READER;
GRANT USAGE ON SCHEMA UCI.PUBLIC TO ROLE DM_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA UCI.PUBLIC TO ROLE DM_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA UCI.PUBLIC TO ROLE DM_READER;
GRANT USAGE ON DATABASE OWID TO ROLE DM_READER;
GRANT USAGE ON SCHEMA OWID.PUBLIC TO ROLE DM_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA OWID.PUBLIC TO ROLE DM_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA OWID.PUBLIC TO ROLE DM_READER;

-- Sample data. If this database is missing in your account, uncomment the next line first:
-- CREATE DATABASE SNOWFLAKE_SAMPLE_DATA FROM SHARE SFC_SAMPLES.SAMPLE_DATA;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE DM_READER;

GRANT ROLE DM_READER TO USER IDENTIFIER($me);

-- Role used only by load_data.py to create tables. It owns the PUBLIC schema of each source database,
-- so it can grant the read-only role access to the tables it loads.
CREATE ROLE IF NOT EXISTS DM_LOADER;
GRANT USAGE ON WAREHOUSE DM_WH TO ROLE DM_LOADER;
GRANT ALL ON DATABASE UCI TO ROLE DM_LOADER;
GRANT ALL ON DATABASE OWID TO ROLE DM_LOADER;
GRANT OWNERSHIP ON SCHEMA UCI.PUBLIC TO ROLE DM_LOADER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA OWID.PUBLIC TO ROLE DM_LOADER COPY CURRENT GRANTS;
GRANT ROLE DM_LOADER TO USER IDENTIFIER($me);

-- Sanity check
USE ROLE DM_READER;
USE WAREHOUSE DM_WH;
SELECT COUNT(*) AS orders FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS;

