-- DataMind Snowflake setup. Run once in a Snowsight worksheet as ACCOUNTADMIN.
-- Uses your own login automatically. If a GRANT ROLE line errors on IDENTIFIER($me),
-- replace IDENTIFIER($me) with your username (run SELECT CURRENT_USER(); to see it).

USE ROLE ACCOUNTADMIN;
SET me = '"' || CURRENT_USER() || '"';  -- quoted so lowercase usernames resolve

CREATE WAREHOUSE IF NOT EXISTS DM_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS DATAMIND;
CREATE SCHEMA IF NOT EXISTS DATAMIND.PUBLIC;

-- Read-only role used by the app (it can only SELECT).
CREATE ROLE IF NOT EXISTS DM_READER;
GRANT USAGE ON WAREHOUSE DM_WH TO ROLE DM_READER;
GRANT USAGE ON DATABASE DATAMIND TO ROLE DM_READER;
GRANT USAGE ON SCHEMA DATAMIND.PUBLIC TO ROLE DM_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA DATAMIND.PUBLIC TO ROLE DM_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA DATAMIND.PUBLIC TO ROLE DM_READER;

-- Sample data. If this database is missing in your account, uncomment the next line first:
-- CREATE DATABASE SNOWFLAKE_SAMPLE_DATA FROM SHARE SFC_SAMPLES.SAMPLE_DATA;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE DM_READER;

GRANT ROLE DM_READER TO USER IDENTIFIER($me);

-- Role used only by load_data.py to create tables.
CREATE ROLE IF NOT EXISTS DM_LOADER;
GRANT USAGE ON WAREHOUSE DM_WH TO ROLE DM_LOADER;
GRANT ALL ON DATABASE DATAMIND TO ROLE DM_LOADER;
GRANT ALL ON SCHEMA DATAMIND.PUBLIC TO ROLE DM_LOADER;
GRANT ROLE DM_LOADER TO USER IDENTIFIER($me);

-- Sanity check
USE ROLE DM_READER;
USE WAREHOUSE DM_WH;
SELECT COUNT(*) AS orders FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS;
